export type Lang = "ru" | "en";
export type TKey = keyof typeof ru;
const DICTS: Record<Lang, Dict> = { ru, en };

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TKey, vars?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const s = localStorage.getItem("kls_lang");
    if (s === "ru" || s === "en") return s;
  } catch {
    /* storage unavailable */
  }
  return navigator.language?.startsWith("ru") || navigator.language?.startsWith("kk") ? "ru" : "ru";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("kls_lang", l);
    } catch {
      /* ignore */
    }
  }, []);
  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useT() {
  const c = useContext(Ctx);
  if (!c) throw new Error("I18nProvider missing");
  return c;
}

/** Translates an API error code. */
export function errText(t: I18n["t"], code: string | undefined): string {
  const key = `err.${code}` as TKey;
  return code && key in ru ? t(key) : t("common.error");
}
